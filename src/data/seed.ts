const daysAgo = (days: number) => {
  const date = new Date("2026-11-03T09:00:00.000Z");
  date.setDate(date.getDate() - days);
  return date.toISOString();
};

const inDays = (days: number, hour = 18) => {
  const date = new Date("2026-11-03T09:00:00.000Z");
  date.setDate(date.getDate() + days);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
};

